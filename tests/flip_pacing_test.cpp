// The flip keeper (hle/flip_pacing.h) replayed against flip timelines
// recorded in Cainhurst's first-arrival cutscene, where one shot after a cut
// (the game's stall: its "pause" here) came back off the tick in three runs of
// four. A model of video.cpp's flip queue and of the game's
// wait - a flip completes on a tick, no sooner than two ticks after the tick
// the command processor queued it in; the game asks for the flip status when
// its frame is ready and waits while the flip two back has not completed - is
// fed each recorded frame's readiness (a frame called off the tick was ready
// just before its call; one called on the tick, just before that tick) and
// when the command processor finished its jobs, which do not move when the
// game is held. The model is checked first: without the keeper it gives back
// the recorded calls. Then:
//   - the keeper puts the runs that came back from the game's pause off the
//     tick (a1, a2, b1) back on it with one kick: calls on the tick, no frame
//     alternation, at most 10 frames over 17.2 ms; and what that costs: how
//     long a finished frame then waits to be queued to be shown;
//   - it moves nothing before the pause, nor in b2, which came back on the
//     tick, and after the game's second pause its calls are the recorded ones;
//   - the two rules it replaced fail: every flip a tick longer drops the game
//     to 40; a hold counted from the game's previous call changes nothing;
//   - made-up timelines: no kick at 57 fps, for one late frame, or while the
//     game's wait blocks; no second kick within 300 ticks; the keeper only at
//     60 on a 60 Hz flip clock.
// Then four deliberate mistakes, each of which must be caught.
