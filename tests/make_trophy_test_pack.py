#!/usr/bin/env python3
"""Writes tests/trophy_test_pack.h: a made-up trophy pack for trophy_pack_test.

Nothing here is from a game: the NP communication ID, the trophy key, the
names and the icon are all invented. The pack is built the way a real
trophy00.trp is (big-endian TRP header and entries, TROP.ESFM encrypted with
AES-128-CBC under the key made from the ID, the first 16 bytes of the entry
the IV), with the system `openssl` doing the AES so the test has a reading of
the format that does not share code with the one it tests.

    python3 tests/make_trophy_test_pack.py > tests/trophy_test_pack.h
"""
import struct
import subprocess
import sys
import zlib

COMM_ID = b"NPWR00000_00"
TROPHY_KEY = bytes(range(16))  # 000102...0f
IV = bytes(range(0xA0, 0xB0))


def openssl_cbc(key, iv, data):
    r = subprocess.run(["openssl", "enc", "-aes-128-cbc", "-nopad", "-K", key.hex(), "-iv", iv.hex()],
                       input=data, capture_output=True, check=True)
    return r.stdout


def png_rgba(w, h, pixel):
    raw = b"".join(b"\x00" + b"".join(bytes(pixel(x, y)) for x in range(w)) for y in range(h))

    def chunk(tag, body):
        c = struct.pack(">I", len(body)) + tag + body
        return c + struct.pack(">I", zlib.crc32(tag + body) & 0xFFFFFFFF)

    return (b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", w, h, 8, 6, 0, 0, 0)) +
            chunk(b"IDAT", zlib.compress(raw, 9)) + chunk(b"IEND", b""))


def icon_pixel(x, y):  # four 4x4 quadrants
    if y < 4:
        return (200, 40, 40, 255) if x < 4 else (40, 200, 40, 255)
    return (40, 40, 200, 128) if x < 4 else (0, 0, 0, 0)


XML = ('<?xml version="1.0" encoding="utf-8"?>\n<trophyconf version="1.1">\n'
       '<title-name>Test Game</title-name>\n'
       '<trophy id="000" hidden="no" ttype="G" pid="-1"><name>Gold &amp; Glory</name>'
       '<detail>First line.\nSecond line.</detail></trophy>\n'
       '<trophy id="001" hidden="yes" ttype="B" pid="-1"><name>Café Bronze</name><detail>x</detail></trophy>\n'
       '<trophy id="002" hidden="no" ttype="S" pid="-1"><name>Silver</name><detail>No icon here.</detail></trophy>\n'
       '<trophy id="003" hidden="no" ttype="P" pid="-1"><name>Everything</name><detail>All of them.</detail></trophy>\n'
       '</trophyconf>\n').encode("utf-8")


def main():
    text_key = openssl_cbc(TROPHY_KEY, bytes(16), COMM_ID.ljust(16, b"\0"))
    padded = XML.ljust((len(XML) + 15) // 16 * 16, b"\0")
    esfm = IV + openssl_cbc(text_key, IV, padded)
    files = [("ICON0.PNG", b"not a trophy file"), ("TROP.ESFM", esfm), ("TROP000.PNG", png_rgba(8, 8, icon_pixel))]
    pos = 0x60 + 0x40 * len(files)
    body = b""
    entries = b""
    for name, data in files:
        entries += struct.pack(">32sQQI", name.encode(), pos + len(body), len(data), 0) + bytes(12)
        body += data
    header = struct.pack(">IIQIII", 0xDCA24D00, 1, pos + len(body), len(files), 0x40, 0).ljust(0x60, b"\0")
    blob = header + entries + body
    out = sys.stdout
    out.write("// Generated by tests/make_trophy_test_pack.py; a made-up pack, nothing from a game.\n#pragma once\n\n")
    out.write("#include <cstddef>\n\n")
    out.write('constexpr char kTestCommId[] = "%s";\n' % COMM_ID.decode())
    out.write('constexpr char kTestTrophyKey[] = "%s";\n\n' % TROPHY_KEY.hex())
    out.write("constexpr unsigned char kTestTrp[] = {")
    for i, b in enumerate(blob):
        out.write(("\n    " if i % 16 == 0 else " ") + "0x%02x," % b)
    out.write("\n};\nconstexpr std::size_t kTestTrpSize = sizeof(kTestTrp);\n")


main()
