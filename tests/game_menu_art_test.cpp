// Bits written least significant first, as BC7 reads them.
struct BitWriter {
    std::uint8_t b[16] = {};
    int at = 0;
    void put(std::uint32_t v, int n) {
        for (int i = 0; i < n; ++i, ++at)
            if ((v >> i) & 1) b[at >> 3] |= static_cast<std::uint8_t>(1 << (at & 7));
    }
};

// A mode 6 block of one colour: both endpoints (r, g, b, a) as 7 bits and a
// p-bit of 1, every index 0 - the colour (v << 1 | 1) in each channel.
void solid_block(std::uint8_t out[16], int r, int g, int b, int a) {
    BitWriter w;
    w.put(1 << 6, 7);
    for (const int c : {r, g, b, a}) {
        w.put(static_cast<std::uint32_t>(c), 7);
        w.put(static_cast<std::uint32_t>(c), 7);
    }
    w.put(1, 1);
    w.put(1, 1);
    std::memcpy(out, w.b, 16);
}

// A mode 1 (two subsets) or mode 2 (three) block of partition part: each
// subset's endpoints e0 and e1, every index 0, or every bit after the
// endpoints 1 (the anchors' indices then one bit short, so a step lower).
void partition_block(std::uint8_t out[16], int mode, int part, const int (*e)[2][3], bool ones) {
    BitWriter w;
    const int subsets = mode == 1 ? 2 : 3, bits = mode == 1 ? 6 : 5;
    w.put(1u << mode, mode + 1);
    w.put(static_cast<std::uint32_t>(part), 6);
    for (int c = 0; c < 3; ++c)
        for (int s = 0; s < subsets; ++s)
            for (int k = 0; k < 2; ++k) w.put(static_cast<std::uint32_t>(e[s][k][c]), bits);
    if (mode == 1) w.put(0, 2);  // its shared p-bits
    if (ones)
        while (w.at < 128) w.put(1, 1);
    std::memcpy(out, w.b, 16);
}

std::uint64_t fnv(const std::vector<std::uint8_t>& v) {
    std::uint64_t h = 0xcbf29ce484222325ull;
    for (const std::uint8_t x : v) {
        h ^= x;
        h *= 0x100000001b3ull;
    }
    return h;
}

void put32(std::vector<std::uint8_t>& b, std::size_t at, std::uint32_t v) {
    for (int i = 0; i < 4; ++i) b[at + i] = static_cast<std::uint8_t>(v >> (8 * i));
}

